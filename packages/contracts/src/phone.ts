import { z } from "zod";

/**
 * Приводит телефонный номер к единому казахстанскому МОБИЛЬНОМУ виду `+77XXXXXXXXX` (11 цифр).
 * Принимает разный пользовательский ввод: `8…`, `+7…`, `7…`, со скобками, пробелами и дефисами.
 * Возвращает нормализованный номер либо `null`, если это не казахстанский мобильный номер.
 *
 * Код +7 общий у Казахстана и России, поэтому различаем их по первой цифре кода зоны:
 * казахстанские мобильные всегда `+7 7XX` (700/701/702/705/707/708/747/771/775/776/777/778…),
 * тогда как российские мобильные `+7 9XX` и стационарные `+7 4XX/8XX` отклоняются — так у
 * админа рабочие ссылки звонок/WhatsApp. Простое правило `7XX` устойчиво к добавлению новых
 * операторских кодов; компромисс — редкие казахстанские городские коды на 7 (Алматы 727,
 * Астана 717) тоже проходят, но реальный ввод (Telegram-контакт) всегда мобильный.
 */
export function normalizeKzPhone(input: string): string | null {
  let digits = input.replace(/\D/g, "");

  // 8XXXXXXXXXX → 7XXXXXXXXXX (привычный для KZ/РФ ввод через 8)
  if (digits.length === 11 && digits.startsWith("8")) {
    digits = "7" + digits.slice(1);
  }

  // 10 цифр без кода страны (например, 701 234 56 78) → добавляем код 7
  if (digits.length === 10) {
    digits = "7" + digits;
  }

  // Строго казахстанский мобильный: код страны 7 + операторский код, начинающийся на 7.
  if (!/^77\d{9}$/.test(digits)) {
    return null;
  }

  return "+" + digits;
}

/**
 * Zod-схема телефона: тримит, нормализует к `+77XXXXXXXXX`, отклоняет всё, что не является
 * казахстанским мобильным номером. Выходной тип — нормализованная строка.
 */
export const kzPhoneSchema = z
  .string({ error: "Укажите номер телефона" })
  .trim()
  .transform((value) => normalizeKzPhone(value))
  .refine((value): value is string => value !== null, {
    error: "Введите казахстанский мобильный номер (например, +7 701 234 56 78)"
  });
